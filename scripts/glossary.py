"""Build and check the book's glossary.

Source of truth: one Markdown file per term in ``src/downcroc/docs/part-iii/glossary``.
Artifact: ``src/downcroc/docs/part-iii/37-glossary.md``, generated deterministically.

Usage:
    uv run python scripts/glossary.py build
    uv run python scripts/glossary.py check
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
GLOSSARY_DIR = REPO / "src/downcroc/docs/part-iii/glossary"
ARTIFACT = REPO / "src/downcroc/docs/part-iii/37-glossary.md"
DOCS_ROOT = REPO / "src/downcroc/docs"
TERM_REF = re.compile(r"\[\[([a-z0-9][a-z0-9_-]*)\]\]")

HEADER = """\
---
title: Glossary
---

<!-- generated by scripts/glossary.py; edit entries in glossary/, not this file -->

# Glossary

Every mechanic word used anywhere in the book is defined here, once, from the
reader's question rather than the mechanism. Pages link to it with
`[[term]]`. An entry that can only be written in mechanism words marks a term
that does not belong in Part I.
"""


@dataclass(frozen=True)
class Entry:
    slug: str
    term: str
    body: str
    see_also: tuple[str, ...]


def _strip(text: str) -> str:
    return text.strip()


def parse_entry(path: Path) -> Entry:
    raw = path.read_text(encoding="utf-8")
    if not raw.startswith("---\n"):
        raise ValueError(f"{path}: missing frontmatter")
    _, rest = raw.split("---\n", 1)
    head, body = rest.split("\n---\n", 1)
    meta: dict[str, str] = {}
    for line in head.splitlines():
        if not line.strip():
            continue
        if ":" not in line:
            raise ValueError(f"{path}: bad frontmatter line: {line!r}")
        key, value = line.split(":", 1)
        meta[key.strip()] = value.strip()
    term = meta.get("term") or path.stem
    slug = path.stem
    see_also = _parse_see_also(meta.get("see_also", ""))
    return Entry(slug=slug, term=term, body=body.strip() + "\n", see_also=see_also)


def _parse_see_also(value: str) -> tuple[str, ...]:
    value = value.strip()
    if not value:
        return ()
    if value.startswith("[") and value.endswith("]"):
        inner = value[1:-1].strip()
        if not inner:
            return ()
        items = [item.strip().strip("\"'") for item in inner.split(",")]
        return tuple(item for item in items if item)
    return tuple(item.strip() for item in value.split(",") if item.strip())


def load_entries() -> list[Entry]:
    if not GLOSSARY_DIR.is_dir():
        raise SystemExit(f"missing glossary directory: {GLOSSARY_DIR}")
    entries = [parse_entry(path) for path in sorted(GLOSSARY_DIR.glob("*.md"))]
    entries.sort(key=lambda entry: (entry.term.lower(), entry.slug))
    return entries


def render(entries: list[Entry]) -> str:
    parts = [HEADER.rstrip() + "\n"]
    current = ""
    for entry in entries:
        letter = entry.term[:1].upper()
        if not letter.isalpha():
            letter = "#"
        if letter != current:
            parts.append(f"\n## {letter}\n")
            current = letter
        parts.append(f"\n### {entry.term}\n\n")
        parts.append(entry.body.rstrip() + "\n")
        if entry.see_also:
            refs = ", ".join(f"[[{item}]]" for item in entry.see_also)
            parts.append(f"\nSee also: {refs}\n")
    return "".join(parts).rstrip() + "\n"


def collect_refs() -> dict[str, set[str]]:
    refs: dict[str, set[str]] = {}
    for path in sorted(DOCS_ROOT.rglob("*.md")):
        if path.resolve() == ARTIFACT.resolve():
            continue
        text = path.read_text(encoding="utf-8")
        for match in TERM_REF.finditer(text):
            refs.setdefault(match.group(1), set()).add(str(path.relative_to(REPO)))
    return refs


def lint(entries: list[Entry]) -> int:
    slugs = {entry.slug for entry in entries}
    problems = 0
    for entry in entries:
        for target in entry.see_also:
            if target not in slugs:
                print(f"see_also: {entry.slug} -> missing {target}", file=sys.stderr)
                problems += 1
    refs = collect_refs()
    for term, files in sorted(refs.items()):
        if term not in slugs:
            where = ", ".join(sorted(files))
            print(f"term: [[{term}]] used but undefined ({where})", file=sys.stderr)
            problems += 1
    for slug in sorted(slugs - set(refs)):
        print(f"orphan: {slug} is defined but never referenced", file=sys.stderr)
    return problems


def cmd_build() -> int:
    entries = load_entries()
    ARTIFACT.write_text(render(entries), encoding="utf-8")
    print(f"wrote {len(entries)} terms to {ARTIFACT.relative_to(REPO)}")
    return 0


def cmd_check() -> int:
    entries = load_entries()
    rendered = render(entries)
    current = ARTIFACT.read_text(encoding="utf-8") if ARTIFACT.exists() else ""
    problems = lint(entries)
    if current != rendered:
        print(f"drift: {ARTIFACT.relative_to(REPO)} is out of date", file=sys.stderr)
        problems += 1
    if problems:
        return 1
    print(f"ok: {len(entries)} terms, no drift")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["build", "check"])
    args = parser.parse_args()
    if args.command == "build":
        return cmd_build()
    return cmd_check()


if __name__ == "__main__":
    raise SystemExit(main())
